let currentLang = 'fr';

function getText(key, params = {}) {
  let text = i18n[currentLang][key] || key;
  for (const [k, v] of Object.entries(params)) {
    text = text.replace(`{${k}}`, v);
  }
  return text;
}

function switchLang(lang) {
  currentLang = lang;
  localStorage.setItem('facealamer-lang', lang);
  document.documentElement.lang = lang === 'fr' ? 'fr' : 'en';
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
      const attr = el.dataset.i18nAttr || 'placeholder';
      el.setAttribute(attr, getText(key));
    } else if (el.dataset.i18nHtml) {
      el.innerHTML = getText(key);
    } else {
      el.textContent = getText(key);
    }
  });
  document.querySelectorAll('.lang-switch button').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === lang);
  });
}

function initI18n() {
  const saved = localStorage.getItem('facealamer-lang');
  if (saved && i18n[saved]) {
    currentLang = saved;
  }
  switchLang(currentLang);
}
